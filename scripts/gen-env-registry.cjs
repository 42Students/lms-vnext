// Generates src/config/env-names.ts from every environment variable the source reads today.
// Run again after adding a variable: the config module and the ratchet then agree on the full list.
const { execSync } = require("child_process");
const fs = require("fs");

const files = execSync("git ls-files src", { encoding: "utf8" }).split("\n").filter((f) => /\.(ts|tsx)$/.test(f));
const names = new Set();
for (const f of files) {
  if (f.startsWith("src/config/")) continue;
  const s = fs.readFileSync(f, "utf8");
  for (const m of s.matchAll(/process\.env(?:\.([A-Za-z_][A-Za-z0-9_]*)|\[\s*["']([A-Za-z_][A-Za-z0-9_]*)["']\s*\])/g)) {
    names.add(m[1] || m[2]);
  }
}
// Names that must stay literal `process.env.X` where they are read, because the bundler replaces them at build time.
const BUNDLER_LITERAL = (n) => n === "NODE_ENV" || n.startsWith("NEXT_");
const list = [...names].filter((n) => !BUNDLER_LITERAL(n)).sort();

const kind = (n) =>
  /DATABASE_URL|^PGADMIN_URL$|^PGOPTIONS$/.test(n) ? (n === "PGOPTIONS" ? "setting" : "secret")
  : /(SECRET|TOKEN|PASSWORD|PRIVATE_KEY|ACCESS_KEY|API_KEY|CLIENT_SECRET|KEY_MATERIAL)/.test(n) || /_KEY$/.test(n) ? "secret"
  : /(_READY|_ENABLED|_ON$|^ENABLE_|_DISABLED$|_FLAG$)/.test(n) ? "flag"
  : "setting";
const group = (n) => n.split("_")[0];

const lines = [];
lines.push("// GENERATED by scripts/gen-env-registry.cjs from the environment variables the source reads. Do not hand-edit the list:");
lines.push("// add a variable by reading it through `env` (src/config/env.ts) and regenerating, so this file stays complete.");
lines.push("// `kind` is a classification by name (secret, flag or setting) used for documentation and boot checks, never for access control.");
lines.push("");
lines.push("export const ENV_NAMES = [");
for (const n of list) lines.push(`  "${n}",`);
lines.push("] as const;");
lines.push("");
lines.push("export type EnvName = (typeof ENV_NAMES)[number];");
lines.push("export type EnvKind = \"secret\" | \"flag\" | \"setting\";");
lines.push("");
lines.push("export const ENV_KIND: Readonly<Record<EnvName, EnvKind>> = {");
for (const n of list) lines.push(`  ${n}: "${kind(n)}",`);
lines.push("};");
lines.push("");
lines.push("export const ENV_GROUP: Readonly<Record<EnvName, string>> = {");
for (const n of list) lines.push(`  ${n}: "${group(n)}",`);
lines.push("};");
lines.push("");
fs.mkdirSync("src/config", { recursive: true });
fs.writeFileSync("src/config/env-names.ts", lines.join("\n"));
const counts = { secret: 0, flag: 0, setting: 0 };
for (const n of list) counts[kind(n)] += 1;
console.log("names:", list.length, counts);
