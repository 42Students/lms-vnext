#!/usr/bin/env node
// Phase 2 coverage ledger (TPO and HR scope): exported service functions, API routes and pages,
// mapped to test files by name reference. Structural evidence only; also flags stub or unguarded pages.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const ROOT = process.cwd();
const norm = (p) => p.split(sep).join("/");
const SCOPE = /(tpo|\bhr\b|[-/_]hr[-/_.]|recruit)/i;

function walk(dir, out = []) {
  let names = [];
  try {
    names = readdirSync(dir);
  } catch {
    return out;
  }
  for (const name of names) {
    if (name === "node_modules" || name === ".next" || name === ".auth") continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

const testTexts = new Map();
const identToTests = new Map();
for (const f of walk(join(ROOT, "tests")).filter((x) => /\.(test|spec)\.(ts|tsx|mjs|js)$/.test(x))) {
  const text = readFileSync(f, "utf8");
  const rel = norm(relative(ROOT, f));
  testTexts.set(rel, text);
  for (const id of new Set(text.match(/[A-Za-z_$][A-Za-z0-9_$]*/g) ?? [])) {
    let s = identToTests.get(id);
    if (!s) identToTests.set(id, (s = new Set()));
    s.add(rel);
  }
}

const MUTATING = /^(create|update|delete|remove|set|save|add|apply|bulk|withdraw|archive|reopen|merge|import|submit|approve|reject|transition|grade|assign|revoke|record|mark|send|publish|cancel|schedule|clone|undo|promote|debar|register|close|accept|decline|confirm|invite|resend|share|unshare|follow|mute|block|unblock|restore|reassign)/i;
const exportRe = /export\s+(?:async\s+)?function\s+([A-Za-z0-9_$]+)|export\s+const\s+([A-Za-z0-9_$]+)\s*=\s*(?:async\s*)?(?:\(|function|[A-Za-z0-9_$]+\s*=>)/g;

const fnRows = [];
for (const f of walk(join(ROOT, "src/modules/placements")).filter((x) => /\.ts$/.test(x) && !/\.(test|spec|d)\.ts$/.test(x))) {
  const rel = norm(relative(ROOT, f));
  if (!SCOPE.test(rel)) continue;
  const src = readFileSync(f, "utf8");
  for (const m of src.matchAll(exportRe)) {
    const name = m[1] ?? m[2];
    fnRows.push({ file: rel, name, tests: [...(identToTests.get(name) ?? [])], mutating: MUTATING.test(name) });
  }
}

const routeRows = [];
for (const f of walk(join(ROOT, "src/app/api")).filter((x) => /route\.ts$/.test(norm(x)))) {
  const rel = norm(relative(ROOT, f));
  if (!SCOPE.test(rel)) continue;
  const src = readFileSync(f, "utf8");
  const methods = [...src.matchAll(/export\s+(?:async\s+function|const)\s+(GET|POST|PUT|PATCH|DELETE)\b/g)].map((m) => m[1]);
  const key = rel.replace(/^src\//, "").replace(/\/route\.ts$/, "");
  const tests = [...testTexts].filter(([, t]) => t.includes(`${key}/route`) || t.includes(`/${key.replace(/^app\/api\//, "api/")}`)).map(([k]) => k);
  routeRows.push({ route: "/" + key.replace(/^app\//, ""), file: rel, methods, tests, mutating: methods.some((m) => m !== "GET") });
}

const GUARD = /(getCurrentRequestContext|requireRequestContext|requireCollegeScope|requireRole|withAuth|requireSession|requireTpo|requireHr|requireRecruiter|assertRole|redirect\()/;
const pageRows = [];
const pageRoots = ["src/app/(authenticated)/tpo", "src/app/(authenticated)/hr", "src/app/(authenticated)/recruiter", "src/app/(authenticated)/admin/placements"];
for (const root of pageRoots) {
  for (const f of walk(join(ROOT, root)).filter((x) => /page\.tsx$/.test(x))) {
    const rel = norm(relative(ROOT, f));
    const src = readFileSync(f, "utf8");
    const stub = /return\s*<div\s*\/>|return\s*<><\/>|return\s*null\s*;?\s*\}/.test(src) && src.length < 400;
    pageRows.push({ file: rel, stub, hasGuardInFile: GUARD.test(src), lines: src.split("\n").length });
  }
}

let md = `# Phase 2 coverage ledger: TPO and HR scope\n\nGenerated by \`node scripts/audit/phase2-ledger.mjs\`. Evidence is structural: a function is "referenced" when its name appears in a test file; a route when a test mentions its path. A floor, not proof of behavioural coverage.\n\nScope filter: placements module files, API routes and pages whose path matches tpo, hr or recruit.\n\n`;
const uncoveredFns = fnRows.filter((r) => r.tests.length === 0);
const uncoveredMutFns = uncoveredFns.filter((r) => r.mutating);
const uncoveredRoutes = routeRows.filter((r) => r.tests.length === 0);
const uncoveredMutRoutes = uncoveredRoutes.filter((r) => r.mutating);
const stubs = pageRows.filter((p) => p.stub);
md += `## Summary\n\n- Exported functions in scope: ${fnRows.length}; never referenced by a test: ${uncoveredFns.length}; mutating-looking: ${uncoveredMutFns.length}\n- API routes in scope: ${routeRows.length}; no test mentions: ${uncoveredRoutes.length}; mutating: ${uncoveredMutRoutes.length}\n- Pages in scope: ${pageRows.length}; stub pages: ${stubs.length}; pages without a guard call in the file itself: ${pageRows.filter((p) => !p.hasGuardInFile).length} (a layout may guard them)\n\n`;
md += `## Stub pages (verify auth and content)\n\n` + (stubs.map((p) => `- ${p.file}`).join("\n") || "- none") + `\n\n`;
md += `## Uncovered mutating functions\n\n` + uncoveredMutFns.map((r) => `- \`${r.name}\` (${r.file})`).join("\n") + `\n\n`;
md += `## Other uncovered functions\n\n` + uncoveredFns.filter((r) => !r.mutating).map((r) => `- \`${r.name}\` (${r.file})`).join("\n") + `\n\n`;
md += `## Uncovered mutating routes\n\n` + uncoveredMutRoutes.map((r) => `- ${r.methods.join("/")} ${r.route}`).join("\n") + `\n\n`;
md += `## Other uncovered routes\n\n` + uncoveredRoutes.filter((r) => !r.mutating).map((r) => `- ${r.route}`).join("\n") + `\n\n`;
md += `## Pages without a guard call in the file\n\n` + pageRows.filter((p) => !p.hasGuardInFile).map((p) => `- ${p.file} (${p.lines} lines${p.stub ? ", STUB" : ""})`).join("\n") + `\n`;
writeFileSync(join(ROOT, "docs/audit/phase2-tpo-hr-coverage-ledger.md"), md);
console.log(JSON.stringify({ fns: fnRows.length, uncoveredFns: uncoveredFns.length, uncoveredMutFns: uncoveredMutFns.length, routes: routeRows.length, uncoveredRoutes: uncoveredRoutes.length, uncoveredMutRoutes: uncoveredMutRoutes.length, pages: pageRows.length, stubs: stubs.length, unguardedPages: pageRows.filter((p) => !p.hasGuardInFile).length }));
