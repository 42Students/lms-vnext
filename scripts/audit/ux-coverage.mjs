// UX coverage matrix: every route, every overlay and every shared component, with the evidence each one has.
// Usage: node scripts/audit/ux-coverage.mjs   (writes docs/audit/ux/COVERAGE-MATRIX.md, exits 1 when gaps remain)
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const walk = (dir, out = []) => {
  for (const name of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, name.name);
    if (name.isDirectory()) {
      if (name.name === "node_modules" || name.name === ".next") continue;
      walk(p, out);
    } else out.push(p);
  }
  return out;
};
const rel = (p) => path.relative(root, p).replaceAll("\\", "/");
const read = (p) => fs.readFileSync(p, "utf8");

const appDir = path.join(root, "src/app");
const all = walk(appDir);
const pages = all.filter((f) => /[\\/]page\.tsx$/.test(f));
const layoutsDirs = new Set(all.filter((f) => /[\\/](loading|error)\.tsx$/.test(f)).map((f) => rel(path.dirname(f))));
const noteFiles = fs.existsSync("docs/audit/ux") ? fs.readdirSync("docs/audit/ux").map((n) => n.toLowerCase()) : [];
const noteText = fs.existsSync("docs/audit/ux")
  ? fs.readdirSync("docs/audit/ux").map((n) => read(path.join("docs/audit/ux", n)).toLowerCase()).join("\n")
  : "";
const tests = walk(path.join(root, "tests")).filter((f) => /\.(test|spec)\.(ts|tsx|mjs)$/.test(f));
const uxTests = tests.filter((f) => /ux/i.test(path.basename(f)));
const uxTestText = uxTests.map(read).join("\n");

function routeOf(file) {
  const r = rel(file).replace(/^src\/app\//, "").replace(/\/?page\.tsx$/, "");
  return "/" + r.split("/").filter((s) => !/^\(.*\)$/.test(s)).join("/");
}
function hasBoundary(file) {
  let d = rel(path.dirname(file));
  const stop = "src/app";
  const hit = { loading: false, error: false };
  while (d.length >= stop.length) {
    if (fs.existsSync(path.join(d, "loading.tsx"))) hit.loading = true;
    if (fs.existsSync(path.join(d, "error.tsx"))) hit.error = true;
    const parent = path.dirname(d).replaceAll("\\", "/");
    if (parent === d) break;
    d = parent;
  }
  return hit;
}
const slug = (route) => route.toLowerCase().replace(/^\//, "").replace(/[\[\]\.]/g, "").replaceAll("/", "-") || "home";

const rows = [];
for (const f of pages) {
  const route = routeOf(f);
  const src = read(f);
  const s = slug(route);
  const noteByName = noteFiles.some((n) => n === s + ".md" || n === s.replace(/\.\.\./g, "") + ".md");
  const noteByMention = noteText.includes("`" + route.toLowerCase() + "`") || noteText.includes("(" + route.toLowerCase() + ")") || noteText.includes(route.toLowerCase() + " ");
  const testByRoute = uxTestText.includes(rel(f)) || uxTestText.includes('"' + route + '"') || uxTestText.includes("'" + route + "'") || uxTestText.includes(route + "/") || uxTestText.includes(route + "`");
  const boundary = hasBoundary(f);
  const usesShared = /from\s+["']@\/components\/ui\//.test(src) || /from\s+["']@\/components\//.test(src);
  rows.push({ route, file: rel(f), note: noteByName || noteByMention, test: testByRoute, loading: boundary.loading, error: boundary.error, shared: usesShared });
}

// overlays: components that open dialogs/drawers/sheets
const comps = walk(path.join(root, "src/components")).filter((f) => /\.tsx$/.test(f));
const overlayRe = /(<Dialog\b|<Drawer\b|<BottomSheet\b|<ConfirmDialog\b|role=["']dialog["']|showModal\(|<dialog\b)/;
const overlays = comps
  .filter((f) => !/components[\\/]ui[\\/]/.test(f))
  .filter((f) => overlayRe.test(read(f)))
  .map((f) => {
    const r = rel(f);
    const base = path.basename(f, ".tsx");
    const covered = uxTestText.includes(base) || noteText.includes(base.toLowerCase()) || uxTestText.includes(r);
    return { file: r, covered };
  });

// shared components need a direct test mention
const ui = comps.filter((f) => /components[\\/]ui[\\/]/.test(f));
const allTestText = tests.map(read).join("\n");
const uiRows = ui.map((f) => {
  const base = path.basename(f, ".tsx");
  return { file: rel(f), tested: allTestText.includes(base) || allTestText.includes(rel(f)) };
});

// raw patterns outside the shared kit
const raw = { table: [], formNoLabelHint: [], targetBlank: [] };
for (const f of comps.concat(pages)) {
  if (/components[\\/]ui[\\/]/.test(f)) continue;
  const s = read(f);
  if (/<table\b/.test(s)) raw.table.push(rel(f));
  if (/target=["']_blank["']/.test(s) && !/rel=["'][^"']*noopener/.test(s)) raw.targetBlank.push(rel(f));
}

const gaps = {
  noNote: rows.filter((r) => !r.note),
  noTest: rows.filter((r) => !r.test),
  noLoading: rows.filter((r) => !r.loading),
  noError: rows.filter((r) => !r.error),
  noShared: rows.filter((r) => !r.shared),
  overlayUncovered: overlays.filter((o) => !o.covered),
  uiUntested: uiRows.filter((u) => !u.tested),
};

let md = "# UX coverage matrix (generated by scripts/audit/ux-coverage.mjs)\n\n";
md += `Routes: ${rows.length}. Overlay-bearing components: ${overlays.length}. Shared UI components: ${uiRows.length}. UX test files: ${uxTests.length}.\n\n`;
md += "## Gap summary\n\n| Check | Gaps |\n|---|---|\n";
for (const [k, v] of Object.entries(gaps)) md += `| ${k} | ${v.length} |\n`;
md += `| raw <table> outside DataTable | ${raw.table.length} |\n| target=_blank without noopener | ${raw.targetBlank.length} |\n\n`;
const section = (title, list, f) => {
  md += `## ${title} (${list.length})\n\n` + (list.length ? list.map(f).join("\n") : "none") + "\n\n";
};
section("Routes without a UX note", gaps.noNote, (r) => `- ${r.route} (${r.file})`);
section("Routes without a UX test mention", gaps.noTest, (r) => `- ${r.route} (${r.file})`);
section("Routes without loading boundary", gaps.noLoading, (r) => `- ${r.route}`);
section("Routes without error boundary", gaps.noError, (r) => `- ${r.route}`);
section("Routes using no shared components", gaps.noShared, (r) => `- ${r.route} (${r.file})`);
section("Overlay components with no UX test/note", gaps.overlayUncovered, (o) => `- ${o.file}`);
section("Shared UI components with no test", gaps.uiUntested, (u) => `- ${u.file}`);
section("Raw <table> outside DataTable", raw.table.map((f) => ({ f })), (x) => `- ${x.f}`);
section("target=_blank without noopener", raw.targetBlank.map((f) => ({ f })), (x) => `- ${x.f}`);
md += "## All routes\n\n| Route | Note | Test | Loading | Error | Shared kit |\n|---|---|---|---|---|---|\n";
for (const r of rows.sort((a, b) => a.route.localeCompare(b.route))) {
  md += `| ${r.route} | ${r.note ? "yes" : "NO"} | ${r.test ? "yes" : "NO"} | ${r.loading ? "yes" : "NO"} | ${r.error ? "yes" : "NO"} | ${r.shared ? "yes" : "NO"} |\n`;
}
fs.mkdirSync("docs/audit/ux", { recursive: true });
fs.writeFileSync("docs/audit/ux/COVERAGE-MATRIX.md", md);
const total = Object.values(gaps).reduce((n, v) => n + v.length, 0) + raw.table.length + raw.targetBlank.length;
console.log(`routes=${rows.length} overlays=${overlays.length} ui=${uiRows.length} gaps=${total}`);
for (const [k, v] of Object.entries(gaps)) console.log(k, v.length);
console.log("rawTable", raw.table.length, "targetBlank", raw.targetBlank.length);
process.exit(total ? 1 : 0);
