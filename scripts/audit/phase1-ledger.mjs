#!/usr/bin/env node
// Phase 1 coverage ledger: maps exported service functions and API routes of the projects and
// placements modules to the test files that reference them. Structural (name reference) evidence only.
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { tmpdir } from "node:os";

const ROOT = process.cwd();
const MODULES = ["src/modules/projects", "src/modules/placements"];
const TEST_DIRS = ["tests"];
const norm = (p) => p.split(sep).join("/");

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name === ".next" || name === ".auth") continue;
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

const testFiles = TEST_DIRS.flatMap((d) => walk(join(ROOT, d))).filter((f) => /\.(test|spec)\.(ts|tsx|mjs|js)$/.test(f));
const identToTests = new Map();
const testTexts = new Map();
for (const f of testFiles) {
  const text = readFileSync(f, "utf8");
  const rel = norm(relative(ROOT, f));
  testTexts.set(rel, text);
  for (const id of new Set(text.match(/[A-Za-z_$][A-Za-z0-9_$]*/g) ?? [])) {
    let s = identToTests.get(id);
    if (!s) identToTests.set(id, (s = new Set()));
    s.add(rel);
  }
}

const exportRe = /export\s+(?:async\s+)?function\s+([A-Za-z0-9_$]+)|export\s+const\s+([A-Za-z0-9_$]+)\s*=\s*(?:async\s*)?(?:\(|function|[A-Za-z0-9_$]+\s*=>)/g;
const modules = {};
for (const mod of MODULES) {
  const files = walk(join(ROOT, mod)).filter((f) => /\.ts$/.test(f) && !/\.(test|spec|d)\.ts$/.test(f));
  const rows = [];
  for (const f of files) {
    const src = readFileSync(f, "utf8");
    const rel = norm(relative(ROOT, f));
    const base = rel.replace(/\.ts$/, "");
    const names = new Set();
    for (const m of src.matchAll(exportRe)) names.add(m[1] ?? m[2]);
    const fileTests = new Set([...testTexts].filter(([, t]) => t.includes(base.replace(/^src\//, ""))).map(([k]) => k));
    for (const name of names) {
      const refs = new Set([...(identToTests.get(name) ?? [])]);
      rows.push({ file: rel, name, tests: [...refs], fileImported: fileTests.size > 0, mutating: /^(create|update|delete|remove|set|save|add|apply|bulk|withdraw|archive|reopen|merge|import|submit|approve|reject|transition|grade|assign|revoke|record|mark|send|publish|cancel|schedule|clone|undo|promote|debar|register)/i.test(name) });
    }
  }
  modules[mod] = rows;
}

const routeFiles = walk(join(ROOT, "src/app/api")).filter((f) => /route\.ts$/.test(norm(f)) && /(project|placement)/i.test(norm(f)));
const routes = routeFiles.map((f) => {
  const rel = norm(relative(ROOT, f));
  const src = readFileSync(f, "utf8");
  const methods = [...src.matchAll(/export\s+(?:async\s+function|const)\s+(GET|POST|PUT|PATCH|DELETE)\b/g)].map((m) => m[1]);
  const key = rel.replace(/^src\//, "").replace(/\/route\.ts$/, "");
  const tests = [...testTexts].filter(([, t]) => t.includes(`${key}/route`) || t.includes(`/${key.replace(/^app\/api\//, "api/")}`)).map(([k]) => k);
  return { route: "/" + key.replace(/^app\//, ""), file: rel, methods, tests, mutating: methods.some((m) => m !== "GET") };
});

let md = `# Phase 1 coverage ledger: projects and placements\n\nGenerated by \`node scripts/audit/phase1-ledger.mjs\`. Evidence is structural: a function is "referenced" when its name appears in a test file; a route is "referenced" when a test mentions its route path. This is a floor, not proof of behavioural coverage (happy path, permission matrix, tenant isolation, state machines, idempotency, audit events and error mapping must still be read in the referenced tests).\n\n`;
const summary = [];
for (const [mod, rows] of Object.entries(modules)) {
  const total = rows.length;
  const uncovered = rows.filter((r) => r.tests.length === 0);
  const uncoveredMut = uncovered.filter((r) => r.mutating);
  summary.push({ mod, total, uncovered: uncovered.length, uncoveredMut: uncoveredMut.length });
  md += `## ${mod}\n\n- Exported functions: ${total}\n- Never referenced by any test: ${uncovered.length}\n- of which mutating-looking (write path): ${uncoveredMut.length}\n\n`;
  md += `### Uncovered mutating functions (highest risk)\n\n`;
  for (const r of uncoveredMut) md += `- \`${r.name}\` (${r.file})\n`;
  md += `\n### Other uncovered functions\n\n`;
  for (const r of uncovered.filter((x) => !x.mutating)) md += `- \`${r.name}\` (${r.file})\n`;
  md += `\n### Covered functions (test count)\n\n`;
  for (const r of rows.filter((x) => x.tests.length > 0)) md += `- \`${r.name}\` (${r.file}): ${r.tests.length} test file(s)\n`;
  md += `\n`;
}
const uncoveredRoutes = routes.filter((r) => r.tests.length === 0);
const uncoveredMutRoutes = uncoveredRoutes.filter((r) => r.mutating);
md += `## API routes (projects and placements)\n\n- Routes: ${routes.length}\n- No test mentions the route path: ${uncoveredRoutes.length}\n- of which mutating (POST/PUT/PATCH/DELETE): ${uncoveredMutRoutes.length}\n\n### Uncovered mutating routes (highest risk)\n\n`;
for (const r of uncoveredMutRoutes) md += `- \`${r.methods.join("|")} ${r.route}\` (${r.file})\n`;
md += `\n### Other uncovered routes\n\n`;
for (const r of uncoveredRoutes.filter((x) => !x.mutating)) md += `- \`${r.methods.join("|")} ${r.route}\` (${r.file})\n`;
md += `\n### Covered routes (test count)\n\n`;
for (const r of routes.filter((x) => x.tests.length > 0)) md += `- \`${r.methods.join("|")} ${r.route}\`: ${r.tests.length} test file(s)\n`;

mkdirSync(join(ROOT, "docs/audit"), { recursive: true });
writeFileSync(join(ROOT, "docs/audit/phase1-coverage-ledger.md"), md);
writeFileSync(join(tmpdir(), "phase1-ledger-scratch.json"), JSON.stringify({ summary, uncoveredMutRoutes, uncoveredMut: Object.fromEntries(Object.entries(modules).map(([m, r]) => [m, r.filter((x) => x.tests.length === 0 && x.mutating)])) }, null, 1));
console.log(JSON.stringify({ summary, routes: routes.length, uncoveredRoutes: uncoveredRoutes.length, uncoveredMutRoutes: uncoveredMutRoutes.length }, null, 1));
