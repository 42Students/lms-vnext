/**
 * Chat-7 static symbol inventory. Run with:
 *   node scripts/audit/generate-chat7-coverage-ledger.mjs
 *
 * References here are only possible test evidence, NOT behavioural coverage.
 * Explicit verification in docs/audit/coverage/courses-ledger.md and
 * projects-learner-ledger-chat-7.md is still required to close a row.
 */
import fs from "node:fs";
import path from "node:path";
import ts from "typescript";

const root=process.cwd();
const sourceRoot=path.join(root,"src");
const testRoot=path.join(root,"tests");
const output=path.join(root,"docs/audit/coverage/chat7-generated-symbol-ledger.md");
function collect(dir){
 if(!fs.existsSync(dir))return [];
 const files=[];
 for(const entry of fs.readdirSync(dir,{withFileTypes:true})){
  const full=path.join(dir,entry.name);
  if(entry.isDirectory())files.push(...collect(full));
  else if(entry.isFile()&&/\.(?:ts|tsx)$/.test(full)&&!full.endsWith(".d.ts"))files.push(full);
 }
 return files;
}
function relative(filename){return path.relative(root,filename).replaceAll(path.sep,"/");}
function area(filename){
 const p=relative(filename);
 if(p.startsWith("src/modules/courses/"))return "Courses service/models";
 if(p.startsWith("src/modules/projects/")&&/\/learner/i.test(p))return "Projects learner services/models";
 if(p.startsWith("src/app/api/courses/")&&p.endsWith("/route.ts"))return "Courses API handlers";
 if(p.startsWith("src/app/api/projects/")&&/learner|own|backlog/i.test(p)&&p.endsWith("/route.ts"))return "Projects learner API handlers";
 if(p.startsWith("src/app/(authenticated)/learn/")&&p.endsWith("/page.tsx"))return "Learner pages";
 if(p.startsWith("src/app/quiz/")&&p.endsWith("/page.tsx"))return "Quiz pages";
 if(p.startsWith("src/app/(authenticated)/admin/")&&/courses|assignments|quizzes|lessons|videos|resources|live-classes|course-progress/i.test(p)&&p.endsWith("/page.tsx"))return "Super Admin content pages";
 if(p.startsWith("src/components/courses/"))return "Course UI components";
 if(p.startsWith("src/components/attendance/"))return "Attendance UI components";
 return null;
}
function namedExports(filename){
 const text=fs.readFileSync(filename,"utf8");
 const source=ts.createSourceFile(filename,text,ts.ScriptTarget.Latest,true,
  filename.endsWith(".tsx")?ts.ScriptKind.TSX:ts.ScriptKind.TS);
 const symbols=new Set();
 function exported(node){
  const mods=ts.canHaveModifiers(node)?ts.getModifiers(node):undefined;
  return Boolean(mods?.some(m=>m.kind===ts.SyntaxKind.ExportKeyword));
 }
 function nameOf(node){return node?.name&&ts.isIdentifier(node.name)?node.name.text:null;}
 for(const stmt of source.statements){
  if(ts.isExportDeclaration(stmt)){
   if(stmt.exportClause&&ts.isNamedExports(stmt.exportClause)){
    for(const spec of stmt.exportClause.elements)symbols.add(spec.name.text);
   }else if(!stmt.exportClause)symbols.add("* re-export");
   continue;
  }
  if(ts.isExportAssignment(stmt)){symbols.add("default");continue;}
  if(!exported(stmt))continue;
  if(ts.isVariableStatement(stmt)){
   for(const decl of stmt.declarationList.declarations){
    if(ts.isIdentifier(decl.name))symbols.add(decl.name.text);
    else symbols.add("(destructured export)");
   }
  }else if(ts.isFunctionDeclaration(stmt)||ts.isClassDeclaration(stmt)||
   ts.isInterfaceDeclaration(stmt)||ts.isTypeAliasDeclaration(stmt)||
   ts.isEnumDeclaration(stmt)){
   symbols.add(nameOf(stmt)||"default");
  }else if(ts.isModuleDeclaration(stmt)){symbols.add(stmt.name.getText(source));}
 }
 return [...symbols].sort();
}
const rows=[];
for(const filename of collect(sourceRoot)){
 const group=area(filename);
 if(!group)continue;
 const symbols=namedExports(filename);
 if(!symbols.length){
  rows.push({area:group,file:relative(filename),symbol:"(no named export; inspect route/page)",hits:[]});
 }else{
  for(const symbol of symbols)rows.push({area:group,file:relative(filename),symbol,hits:[]});
 }
}
const referenced=new Set(rows.map(row=>row.symbol).filter(s=>/^[A-Za-z_$][\w$]*$/.test(s)));
const candidates=new Map();
for(const file of collect(testRoot)){
 const content=fs.readFileSync(file,"utf8");
 const names=new Set(content.match(/\b[A-Za-z_$][\w$]*\b/g)??[]);
 for(const name of names){
  if(!referenced.has(name))continue;
  const list=candidates.get(name)??[];
  if(list.length<5)list.push(relative(file));
  candidates.set(name,list);
 }
}
for(const row of rows)row.hits=candidates.get(row.symbol)??[];
rows.sort((a,b)=>a.area.localeCompare(b.area)||a.file.localeCompare(b.file)||a.symbol.localeCompare(b.symbol));
const groups=[...new Set(rows.map(r=>r.area))];
const escapeCell=v=>String(v).replaceAll("|","\\|").replaceAll("\n"," ");
const lines=[
 "# Chat-7 generated symbol/route/page inventory",
 "",
 "Generated by `node scripts/audit/generate-chat7-coverage-ledger.mjs`.",
 "**No item below is marked behaviourally covered.** A symbol name appearing in a test is only a search lead; a direct role/tenant/concurrency behavioural test must be inspected and must pass CI before closure.",
 "",
 `Summary: ${rows.length} source/export entries across ${new Set(rows.map(r=>r.file)).size} files. ${rows.filter(r=>!r.hits.length).length} entries have no candidate test references.`,
 "",
];
for(const group of groups){
 lines.push(`## ${group}`,"","| Source file | Export/handler | Test files mentioning symbol (max 5) | Status |","|---|---|---|---|");
 for(const row of rows.filter(r=>r.area===group)){
  lines.push(`| \`${escapeCell(row.file)}\` | \`${escapeCell(row.symbol)}\` | ${row.hits.map(x=>`\`${escapeCell(x)}\``).join(", ")||"No candidate"} | ${row.hits.length?"OPEN — evidence needs review":"OPEN — direct test needed"} |`);
 }
 lines.push("");
}
fs.mkdirSync(path.dirname(output),{recursive:true});
fs.writeFileSync(output,lines.join("\n")+"\n");
process.stdout.write(`Wrote ${relative(output)} (${rows.length} entries)\n`);
