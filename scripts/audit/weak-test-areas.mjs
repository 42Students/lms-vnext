// Finds weakly tested areas: for every src/modules/<module>, how many source files are referenced by any test,
// how many exported functions are named in tests, and test count mentions. Output: docs/audit/coverage/WEAK-AREAS.md
// Usage: node scripts/audit/weak-test-areas.mjs
import fs from "node:fs";
import path from "node:path";

const walk = (dir, out = []) => {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === "node_modules" || e.name === ".next") continue;
      walk(p, out);
    } else out.push(p);
  }
  return out;
};
const norm = (p) => p.split(path.sep).join("/");
const tests = walk("tests").map(norm).filter((f) => /\.(test|spec)\.(ts|tsx|mjs)$/.test(f));
const testText = tests.map((f) => fs.readFileSync(f, "utf8")).join("\n");
const integ = tests.filter((f) => /integration|db|postgres/i.test(f)).length;

const modules = fs.readdirSync("src/modules", { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name);
const rows = [];
for (const m of modules) {
  const files = walk(path.join("src/modules", m)).map(norm).filter((f) => /\.(ts|tsx)$/.test(f) && !/\.d\.ts$/.test(f));
  let referenced = 0;
  let exportsTotal = 0;
  let exportsNamed = 0;
  const untestedFiles = [];
  for (const f of files) {
    const base = path.posix.basename(f).replace(/\.(ts|tsx)$/, "");
    const importPath = f.replace(/^src\//, "@/").replace(/\.(ts|tsx)$/, "");
    const src = fs.readFileSync(f, "utf8");
    const isRef = testText.includes(importPath) || testText.includes(`/${base}"`) || testText.includes(`/${base}'`) || testText.includes(f);
    if (isRef) referenced++;
    else untestedFiles.push(f);
    for (const m2 of src.matchAll(/export\s+(?:async\s+)?(?:function|const)\s+([A-Za-z0-9_]+)/g)) {
      exportsTotal++;
      if (testText.includes(m2[1])) exportsNamed++;
    }
  }
  const lines = files.reduce((n, f) => n + fs.readFileSync(f, "utf8").split("\n").length, 0);
  rows.push({ m, files: files.length, referenced, exportsTotal, exportsNamed, lines, untestedFiles,
    fileCov: files.length ? referenced / files.length : 1, exportCov: exportsTotal ? exportsNamed / exportsTotal : 1 });
}
rows.sort((a, b) => a.exportCov - b.exportCov || b.lines - a.lines);
let md = "# Weak test areas (generated by scripts/audit/weak-test-areas.mjs)\n\n";
md += `Test files: ${tests.length}. Integration-style test files: ${integ}. Heuristic: a source file counts as tested when a test imports or names it; an export counts as covered when a test names it. Treat low numbers as a to-do list, then verify depth by reading tests.\n\n`;
md += "| Module | Files | Files referenced | File cov | Exports | Exports named | Export cov | Lines |\n|---|---|---|---|---|---|---|---|\n";
for (const r of rows) md += `| ${r.m} | ${r.files} | ${r.referenced} | ${(r.fileCov * 100).toFixed(0)}% | ${r.exportsTotal} | ${r.exportsNamed} | ${(r.exportCov * 100).toFixed(0)}% | ${r.lines} |\n`;
md += "\n## Source files with no test reference, by module (weakest first)\n\n";
for (const r of rows) {
  if (!r.untestedFiles.length) continue;
  md += `### ${r.m} (${r.untestedFiles.length})\n\n` + r.untestedFiles.map((f) => `- ${f}`).join("\n") + "\n\n";
}
fs.mkdirSync("docs/audit/coverage", { recursive: true });
fs.writeFileSync("docs/audit/coverage/WEAK-AREAS.md", md);
console.log(rows.slice(0, 12).map((r) => `${r.m}: files ${r.referenced}/${r.files}, exports ${r.exportsNamed}/${r.exportsTotal}`).join("\n"));
