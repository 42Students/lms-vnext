#!/usr/bin/env bash
# Refreshes the audit closure tracker from origin/main plus the lane branches and pushes the
# result to main. Never touches the main checkout: everything happens in a temporary worktree.
#
#   bash scripts/audit/refresh-tracker.sh            # run from anywhere inside the repo
#   NO_PUSH=1 bash scripts/audit/refresh-tracker.sh  # generate and commit locally in the temp worktree, do not push
set -euo pipefail

REPO="$(git rev-parse --show-toplevel)"
cd "$REPO"
git fetch origin --quiet

TMP="$(mktemp -d "${TMPDIR:-/tmp}/lms-tracker.XXXXXX")"
WT="$TMP/wt"
cleanup() { git -C "$REPO" worktree remove --force "$WT" >/dev/null 2>&1 || true; rm -rf "$TMP" || true; git -C "$REPO" worktree prune || true; }
trap cleanup EXIT

git worktree add --detach "$WT" origin/main >/dev/null
cd "$WT"

node scripts/audit/build-gap-register.mjs

FILES=(docs/audit/gap-register.md docs/audit/PROGRESS.md docs/audit/live-check-list.md docs/audit/progress-history.csv docs/audit/tracker-data.json docs/audit/tracker-summary.json)
git add -- "${FILES[@]}"

# Ignore the generation timestamp lines when deciding whether anything changed.
CHANGED=0
if ! git diff --cached --quiet; then
  if git diff --cached -U0 -- "${FILES[@]}" | grep -E '^[+-]' | grep -vE '^(\+\+\+|---)' \
      | grep -vE 'Generated by `node scripts/audit/build-gap-register.mjs` on |"generatedAt"' | grep -q .; then
    CHANGED=1
  fi
fi
if [ "$CHANGED" = "0" ]; then
  echo "tracker: nothing changed, nothing to commit"
  exit 0
fi

git commit --quiet -m "chore(audit): refresh tracker

Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>"

if [ "${NO_PUSH:-0}" = "1" ]; then
  echo "tracker: committed in temporary worktree (NO_PUSH=1), not pushed"
  exit 0
fi

# Push, rebasing onto the latest main when other lanes pushed in between. Generated files only
# conflict with themselves, so on a conflict regenerate them on top of the new main and retry.
for attempt in 1 2 3; do
  git fetch origin --quiet
  if git rebase origin/main >/dev/null 2>&1; then
    if git push origin HEAD:main; then echo "tracker: pushed"; exit 0; fi
  else
    git rebase --abort >/dev/null 2>&1 || true
    git reset --hard origin/main >/dev/null
    node scripts/audit/build-gap-register.mjs >/dev/null
    git add -- "${FILES[@]}"
    git commit --quiet -m "chore(audit): refresh tracker

Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>" || { echo "tracker: nothing to commit after rebase"; exit 0; }
    if git push origin HEAD:main; then echo "tracker: pushed"; exit 0; fi
  fi
done
echo "tracker: push failed after 3 attempts" >&2
exit 1
