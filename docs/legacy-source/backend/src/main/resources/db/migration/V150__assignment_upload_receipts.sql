CREATE TABLE IF NOT EXISTS assignment_upload_receipt (
    id INT NOT NULL AUTO_INCREMENT,
    receipt_id VARCHAR(64) NOT NULL,
    storage_key VARCHAR(1024) NOT NULL,
    public_url VARCHAR(2048) NULL,
    folder VARCHAR(80) NULL,
    upload_type VARCHAR(80) NULL,
    owner_user_id INT NOT NULL,
    owner_user_type VARCHAR(40) NULL,
    lesson_content_id INT NULL,
    declared_content_type VARCHAR(255) NULL,
    declared_content_length BIGINT NULL,
    actual_content_type VARCHAR(255) NULL,
    actual_content_length BIGINT NULL,
    expires_at DATETIME NULL,
    consumed_at DATETIME NULL,
    student_assignment_id INT NULL,
    created_at DATETIME NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    is_deleted BOOLEAN DEFAULT FALSE,
    PRIMARY KEY (id),
    UNIQUE KEY uq_assignment_upload_receipt_id (receipt_id),
    KEY idx_assignment_upload_receipt_storage_key (storage_key(255)),
    KEY idx_assignment_upload_receipt_owner (owner_user_id, owner_user_type),
    KEY idx_assignment_upload_receipt_lesson (lesson_content_id),
    KEY idx_assignment_upload_receipt_consumed (consumed_at)
);
