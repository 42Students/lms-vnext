CREATE TABLE IF NOT EXISTS project_activity_event (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    project_id INT NOT NULL,
    project_slug VARCHAR(120) NOT NULL,
    event_key VARCHAR(120) NOT NULL,
    event_type VARCHAR(60) NOT NULL,
    title VARCHAR(200) NOT NULL,
    summary TEXT NULL,
    source_tab VARCHAR(40) NULL,
    entity_type VARCHAR(60) NULL,
    entity_id VARCHAR(120) NULL,
    actor_user_id INT NULL,
    actor_user_type VARCHAR(20) NULL,
    actor_name VARCHAR(160) NULL,
    metadata_json JSON NULL,
    is_deleted TINYINT(1) NOT NULL DEFAULT 0,
    created_by INT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by INT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_by INT NULL,
    deleted_at DATETIME NULL,
    INDEX idx_project_activity_project (project_id),
    INDEX idx_project_activity_created_at (created_at),
    INDEX idx_project_activity_event_key (event_key)
);
