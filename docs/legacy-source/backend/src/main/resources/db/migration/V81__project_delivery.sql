CREATE TABLE IF NOT EXISTS project_delivery (
    id INT NOT NULL AUTO_INCREMENT,
    created_at DATETIME NULL,
    updated_at DATETIME NULL,
    is_deleted BOOLEAN DEFAULT FALSE,
    project_id INT NOT NULL,
    status VARCHAR(60) DEFAULT 'Draft',
    snapshot TEXT NULL,
    notes TEXT NULL,
    feedback TEXT NULL,
    attachment_url TEXT NULL,
    revision_count INT DEFAULT 0,
    draft_saved_at DATETIME NULL,
    draft_saved_by_id INT NULL,
    draft_saved_by_name VARCHAR(160) NULL,
    submitted_at DATETIME NULL,
    submitted_by_id INT NULL,
    submitted_by_name VARCHAR(160) NULL,
    submitted_by_type VARCHAR(20) NULL,
    review_status VARCHAR(60) NULL,
    reviewed_at DATETIME NULL,
    reviewed_by_id INT NULL,
    reviewed_by_name VARCHAR(160) NULL,
    reviewed_by_type VARCHAR(20) NULL,
    last_updated_at DATETIME NULL,
    last_updated_by_id INT NULL,
    last_updated_by_name VARCHAR(160) NULL,
    last_updated_by_type VARCHAR(20) NULL,
    locked_at DATETIME NULL,
    locked_by_id INT NULL,
    locked_by_name VARCHAR(160) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_project_delivery_project (project_id),
    KEY idx_project_delivery_project (project_id, is_deleted),
    CONSTRAINT fk_project_delivery_project FOREIGN KEY (project_id) REFERENCES project_workspace(id)
);
